"""言語タグ（小文字）から日本語の言語名への表。"""


def name(tag: str) -> str:
    """言語タグに対応する日本語の言語名を返す。

    Parameters
    ----------
    tag : str
        BCP 47 の言語タグ（``en``・``en-US``・``zh-Hans`` など）。

    Returns
    -------
    str
        日本語の言語名。表に無いタグは、渡されたタグをそのまま返す。
    """
    key = tag.strip()
    lowered = key.lower()
    if lowered in _NAMES:
        return _NAMES[lowered]
    base = lowered.split("-", 1)[0]
    return _NAMES.get(base, key)
